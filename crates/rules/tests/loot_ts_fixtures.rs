//! Golden fixture for the TypeScript mirror of the chest tables and budget check
//! (`app/src/chain/loot.ts`). Test-only: no crate logic lives here.
//!
//! The fixture holds the tier limits (`LootTuning` through `map_rules`, the tier's top level),
//! the shipped reward tables as the builder sees them, and a seeded set of
//! `deadroll_mapcheck::loot::check_tables` cases. When a rule or a number changes, regenerate it
//! and update the TS mirror:
//!
//! ```text
//! UPDATE_TS_FIXTURES=1 cargo test -p deadroll-rules --features serde --test loot_ts_fixtures
//! ```
#![cfg(feature = "serde")]
use std::{fs, path::PathBuf};

use deadroll_mapcheck::{
    limits::{tier_limits, TIER_MAX, TIER_MIN},
    loot::{check_tables, MapLoot},
};
use deadroll_rules::{loot::map_rules, registry::Registry, BalanceConfig};
use deadroll_types::{CHESTS_MAX, NO_TABLE, PARTY_MAX};
use serde_json::{json, Value};

const CASES: usize = 600;
/// Fixed seed; changing it rewrites the fixture.
const SEED: u64 = 0xD3AD_0011_C4E5_0001;

fn fixture_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../app/src/chain/__fixtures__/loot.json")
}

/// Small deterministic generator (SplitMix64), so the fixture is stable across runs.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }
}

#[test]
fn loot_check_matches_the_ts_fixture() {
    let registry = Registry::shipped().unwrap();
    let tuning = &BalanceConfig::DEFAULT.loot;
    let ids: Vec<u8> = (0..=u8::MAX)
        .filter(|id| registry.reward_table(*id).is_some())
        .collect();
    let table_of = |id: u8| registry.reward_table(id).map(|t| t.rules());

    let tiers: Vec<Value> = (TIER_MIN..=TIER_MAX)
        .map(|tier| {
            let r = map_rules(tuning, tier);
            json!({
                "tier": tier,
                "levelCap": tier_limits(tier).unwrap().level_max,
                "chests": r.chests,
                "budget": r.budget,
                // u64 mask as a decimal string: JSON numbers stop at 2^53.
                "allowed": r.allowed.to_string(),
            })
        })
        .collect();
    let tables: Vec<Value> = ids
        .iter()
        .map(|&id| {
            let t = table_of(id).unwrap();
            json!({ "id": id, "levelBase": t.level_base, "levelMax": t.level_max, "cost": t.cost })
        })
        .collect();

    // Ids around the shipped ones, an unknown id and NO_TABLE, so every rule is hit both ways.
    let max_id = *ids.last().unwrap();
    let pick = |rng: &mut Rng| -> u8 {
        match rng.below(12) {
            0 => NO_TABLE,
            1 => max_id + 1,
            _ => ids[rng.below(ids.len())],
        }
    };
    let mut rng = Rng(SEED);
    let cases: Vec<Value> = (0..CASES)
        .map(|_| {
            let tier = TIER_MIN + rng.below((TIER_MAX - TIER_MIN + 1) as usize) as u8;
            // Mostly in range: the out-of-range cases are refused before anything else.
            let min_players = match rng.below(10) {
                0 => 0,
                1 => PARTY_MAX as u8 + 1,
                _ => 1 + rng.below(PARTY_MAX) as u8,
            };
            let count = match rng.below(10) {
                0 => CHESTS_MAX + 1,
                _ => rng.below(3),
            };
            let chests: Vec<u8> = (0..count).map(|_| pick(&mut rng)).collect();
            let boss = pick(&mut rng);
            let loot = MapLoot { min_players, rules: map_rules(tuning, tier), table_of };
            let level_cap = tier_limits(tier).unwrap().level_max;
            let result = match check_tables(level_cap, &chests, boss, &loot) {
                Ok(spent) => json!({ "ok": spent }),
                Err(e) => json!({ "err": format!("{e:?}") }),
            };
            json!({ "tier": tier, "minPlayers": min_players, "chests": chests, "boss": boss, "result": result })
        })
        .collect();

    let fixture = json!({
        "note": "generated by crates/rules/tests/loot_ts_fixtures.rs",
        "noTable": NO_TABLE,
        "chestsMax": CHESTS_MAX,
        "tiers": tiers,
        "tables": tables,
        "cases": cases,
    });
    let text = serde_json::to_string(&fixture).unwrap() + "\n";
    let path = fixture_path();
    if std::env::var_os("UPDATE_TS_FIXTURES").is_some() {
        fs::write(&path, &text).unwrap();
    }
    let committed = fs::read_to_string(&path).unwrap_or_default().replace("\r\n", "\n");
    assert!(
        committed == text,
        "stale fixture: run UPDATE_TS_FIXTURES=1 cargo test -p deadroll-rules --features serde --test loot_ts_fixtures"
    );
}
